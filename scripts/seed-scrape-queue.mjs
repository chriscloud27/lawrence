// Generates supabase/seed_scrape_queue.sql: one scrape_queue row per school.
// Thailand URLs are derived from the chatbot seed CSV (slug from name);
// UK URLs are the curated Doris list. Doris slugs are best-effort — verify
// against live pages before a production run.
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url).pathname;
const DORIS = 'https://www.doris.school/schools';

const slugify = (s) =>
  s.toLowerCase().normalize('NFKD').replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-').replace(/-+/g, '-');

// Thailand — from src/Chatbot/data/thailand-schools-seed.csv (name is col 1)
const csv = readFileSync(`${ROOT}src/Chatbot/data/thailand-schools-seed.csv`, 'utf8').trim().split('\n').slice(1);
const thUrls = csv.map((line) => `${DORIS}/thailand/${slugify(line.split(',')[0])}`);

// UK — curated Doris directory slugs
const ukUrls = [
  'st-edwards-school', 'eton-college', 'harrow-school', 'rugby-school', 'winchester-college',
  'cheltenham-ladies-college', 'marlborough-college', 'charterhouse', 'shrewsbury-school', 'tonbridge-school',
].map((slug) => `${DORIS}/united-kingdom/${slug}`);

const urls = [...ukUrls, ...thUrls];
const values = urls.map((u) => `    ('${u.replace(/'/g, "''")}')`).join(',\n');

// scrape_queue.url has no UNIQUE constraint, so guard against re-runs with NOT EXISTS.
const sql = `-- Seed scrape_queue with Doris school URLs (${ukUrls.length} UK + ${thUrls.length} Thailand).
-- Generated by scripts/seed-scrape-queue.mjs. Re-runnable (skips URLs already queued).
-- NOTE: Thailand slugs are derived from school names and are best-effort;
-- verify against live Doris pages before a production scrape run.

INSERT INTO scrape_queue (url, status)
SELECT v.url, 'pending'
FROM (VALUES
${values}
) AS v(url)
WHERE NOT EXISTS (SELECT 1 FROM scrape_queue q WHERE q.url = v.url);
`;

writeFileSync(`${ROOT}supabase/seed_scrape_queue.sql`, sql);
console.log(`wrote supabase/seed_scrape_queue.sql — ${urls.length} URLs (${ukUrls.length} UK, ${thUrls.length} TH)`);
